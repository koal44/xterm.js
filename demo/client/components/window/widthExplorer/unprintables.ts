let unprintableTable: MeasuredTable | undefined;
function getUnprintableTable(): MeasuredTable {
  if (unprintableTable) return unprintableTable;
  const t = new MeasuredTable('unprintables');
  for (const r of unprintableRanges) {
    t.addRange({ start: r.start, end: r.end });
  }
  unprintableTable = t;
  return t;
}

export function ignoreUnprintablesInTable(table: MeasuredTable, label: string): MeasuredTable {
  const hideUnprintablesJoinFn: CanMergeRangeFn = (last, next) => {
    if (MeasuredWidths.equal(last.widths, next.widths)) return true;
    for (let cp = next.start; cp <= next.end; cp++) {
      if (!getUnprintableTable().has(cp)) return false;
    }
    return true;
  };

  const out = new MeasuredTable(label);
  for (const r of table._ranges) {
    out.addRange(r, hideUnprintablesJoinFn);
  }
  return out;
}